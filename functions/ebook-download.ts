// /ebook-download — session-verified delivery of a direct-sale eBook (the store's ONE download endpoint).
//
// THE BIBLE EBOOK (FHB /ebook-checkout, unchanged since v1):
//   GET /ebook-download?s=<checkout_session_id>            → thank-you page + download button
//   GET /ebook-download?s=<checkout_session_id>&dl=epub    → streams the EPUB (attachment)
// A BOOK'S EBOOK (Kevin 2026-11-16 "We point to our own ebook sales"; sold through SMP /store-checkout, Option C):
//   GET /ebook-download?s=<sid>                            → Stripe says paid + ebook_direct + ebook_sku → 302 to the
//                                                            SIGNED link below (Stripe's success_url cannot carry it)
//   GET /ebook-download?s=<sid>&e=<sku>&t=<sig>[&dl=epub]  → the signature (src/lib/ebookLink.ts) must verify FIRST (a
//                                                            tampered link never reaches Stripe), then the session must
//                                                            be paid, ebook_direct, and have sold exactly <sku>
// SMP /ebook-download is a thin proxy to this one (SMP's Pages project has no R2 binding), so an SMP buyer stays on
// spiritmediapublishing.com. Every file lives in the private R2 bucket (FHB_EBOOK); nothing is public. DRM-free.

import ebookFiles from '../src/data/ebook-files.json' with { type: 'json' };
import {
	SID_RE,
	sessionGrantsEbook,
	signEbookLink,
	verifyEbookLink,
} from '../src/lib/ebookLink.ts';
import { EBOOK_SKUS } from '../src/lib/storeEngine.ts';
import EBOOK from './ebook-current.json' with { type: 'json' };

interface Env {
	STRIPE_FHB_SECRET_KEY?: string;
	STRIPE_PRINT_WEBHOOK_SECRET?: string;
	FHB_EBOOK?: R2Bucket;
}

// Which object ships is decided by the eBook RECORD (projects/fhb-ebook/epub-manifest.json),
// not by this file: ebook-current.json is a derived view written by
// bin/fhb-ebook-config.py --write, and a daily reconcile checks the R2 object's sha256
// against the record. Next edition = promote -> upload to the new key -> --write.
// (Until 2026-09-14 this hard-coded the v21 key and served a pre-2026.6 book.)
const EPUB_KEY: string = EBOOK.key;
const EPUB_NAME: string = EBOOK.filename;
// A book eBook's object (generated by bin/fhb-ebook-config.py --smp from the item-3 file record).
const FILES = (ebookFiles as { files: Record<string, { key: string; filename: string }> }).files;

type Session = {
	id?: string;
	payment_status?: string;
	metadata?: Record<string, string> | null;
};
async function getSession(env: Env, sid: string): Promise<Session | null> {
	if (!SID_RE.test(sid)) return null;
	const r = await fetch(`https://api.stripe.com/v1/checkout/sessions/${sid}`, {
		headers: { Authorization: `Bearer ${env.STRIPE_FHB_SECRET_KEY}` },
	});
	return r.ok ? ((await r.json()) as Session) : null;
}

const page = (body: string, smp = false, status = 200) =>
	new Response(
		`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>${smp ? 'Your eBook' : 'Your Father’s Heart Bible eBook'}</title><style>body{font-family:system-ui,-apple-system,sans-serif;background:${smp ? '#f7f5f2' : '#faf6f2'};color:#1a1c1c;display:flex;min-height:100vh;align-items:center;justify-content:center;margin:0;padding:1.5rem}.card{max-width:34rem;text-align:center;background:#fff;border:1px solid ${smp ? '#ddd7cf' : '#e4bdc4'};border-radius:1rem;padding:2.5rem}a.btn{display:inline-block;background:${smp ? '#c0392b' : '#b60057'};color:#fff;text-decoration:none;font-weight:700;padding:0.85rem 1.8rem;border-radius:999px;margin-top:1rem}h1{font-size:1.6rem;margin:0 0 0.5rem}p{color:${smp ? '#3f3f46' : '#5b3f46'};line-height:1.6}</style></head><body><div class="card">${body}</div></body></html>`,
		{
			status,
			headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' },
		},
	);
const REFUSED = (smp = false) =>
	page(
		'<h1>We couldn’t verify that purchase</h1><p>This download link is invalid or expired. If you just bought the eBook and see this, email <a href="mailto:hello@spiritmediapublishing.com">hello@spiritmediapublishing.com</a> and we’ll sort it out.</p>',
		smp,
		403,
	);
const UNAVAILABLE = (smp = false) =>
	page(
		'<h1>File temporarily unavailable</h1><p>Please email <a href="mailto:hello@spiritmediapublishing.com">hello@spiritmediapublishing.com</a>.</p>',
		smp,
		503,
	);
const esc = (s: string) =>
	s.replace(
		/[&<>"]/g,
		(c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c] as string,
	);

export const onRequestGet: PagesFunction<Env> = async ({ request, env }) => {
	const url = new URL(request.url);
	const sid = url.searchParams.get('s') || '';
	const sku = url.searchParams.get('e');
	const sig = url.searchParams.get('t') || '';
	const dl = url.searchParams.get('dl');

	if (!env.STRIPE_FHB_SECRET_KEY || !env.FHB_EBOOK) {
		return page(
			'<h1>Almost there</h1><p>Direct downloads are being switched on. Please check back shortly — your purchase is safe.</p>',
		);
	}

	// A BOOK'S EBOOK: the signed link. Signature first (no Stripe call for a forged or tampered link), then Stripe.
	if (sku !== null) {
		if (!(await verifyEbookLink(env.STRIPE_PRINT_WEBHOOK_SECRET, sid, sku, sig)))
			return REFUSED(true);
		const s = await getSession(env, sid);
		if (!sessionGrantsEbook(s, sid, sku)) return REFUSED(true);
		const smp = s?.metadata?.window !== 'fhb';
		const f = FILES[sku];
		if (!f) return UNAVAILABLE(smp);
		if (dl === 'epub') {
			const obj = await env.FHB_EBOOK.get(f.key);
			if (!obj) return UNAVAILABLE(smp);
			return new Response(obj.body, {
				headers: {
					'content-type': 'application/epub+zip',
					'content-disposition': `attachment; filename="${f.filename}"`,
					'cache-control': 'no-store',
				},
			});
		}
		const title = EBOOK_SKUS[sku]?.title ?? 'Your eBook';
		return page(
			`<h1>Thank you — your eBook is ready</h1><p><strong>${esc(title)}</strong></p><p>It’s a DRM-free EPUB — open it in Apple Books, Google Play Books, or any reader. The same link is in your confirmation email.</p><a class="btn" href="/ebook-download?s=${encodeURIComponent(sid)}&amp;e=${encodeURIComponent(sku)}&amp;t=${sig}&amp;dl=epub">Download EPUB →</a>`,
			smp,
		);
	}

	const s = await getSession(env, sid);
	if (!(s?.payment_status === 'paid' && s.metadata?.kind === 'ebook_direct')) return REFUSED();

	// Stripe's success redirect for a book's eBook carries only the session: sign it here and send the buyer on.
	if (s.metadata?.ebook_sku) {
		const t = await signEbookLink(env.STRIPE_PRINT_WEBHOOK_SECRET, sid, s.metadata.ebook_sku);
		if (!t) return REFUSED(true);
		return new Response(null, {
			status: 302,
			headers: {
				location: `/ebook-download?s=${encodeURIComponent(sid)}&e=${encodeURIComponent(s.metadata.ebook_sku)}&t=${t}`,
				'cache-control': 'no-store',
			},
		});
	}

	// THE BIBLE EBOOK (unchanged).
	if (dl === 'epub') {
		const obj = await env.FHB_EBOOK.get(EPUB_KEY);
		if (!obj) return UNAVAILABLE();
		return new Response(obj.body, {
			headers: {
				'content-type': 'application/epub+zip',
				'content-disposition': `attachment; filename="${EPUB_NAME}"`,
				'cache-control': 'no-store',
			},
		});
	}

	// Thank-you page with the download button (re-verifies on click).
	return page(
		`<h1>Thank you — welcome home</h1><p>Your Father’s Heart Bible eBook is ready. It’s a DRM-free EPUB — open it in Apple Books, Google Play Books, or any reader.</p><a class="btn" href="/ebook-download?s=${encodeURIComponent(sid)}&dl=epub">Download EPUB →</a>`,
	);
};
