// node scripts/sync-store-engine.mjs [--check] [--from <SMP dir>]   (SMP store engine, plan 3fb Phase 3, 2026-11-13)
//
// ONE ENGINE, ONE MASTER = SMP (Kevin 2026-11-16 "1 store SMP. 2 shop windows FHB and SMP"; pmprint/c4bbc2d6).
// The store engine (catalogue, prices, discounts, far-band, margin floor, Stripe sale metadata and the order -> Stripe
// Checkout form) lives in the SMP repo, src/store-engine/ (lib/ + data/). An SMP price change is an SMP commit only.
// FHB carries a BYTE-IDENTICAL copy at src/lib/ + src/data/ (same relative layout, so imports are untouched) because
// FHB's /dvc-checkout and pages import it. This SAME script (byte-identical in both repos) does both ends:
//
//   in SMP  node scripts/sync-store-engine.mjs            stamp src/store-engine/MANIFEST.json (sha256 per file) after
//                                                          editing the engine; commit both. That is the whole SMP flow.
//           node scripts/sync-store-engine.mjs --check    exit 1 if an engine file differs from the manifest
//                                                          (scripts/store-engine-sync.test.mjs runs it in the build)
//   in FHB  node scripts/sync-store-engine.mjs            copy SMP's master (origin/dev, fetched; or --from <dir> = a
//                                                          working tree) into src/lib + src/data, refusing a master
//                                                          whose files do not match its own manifest, and write the
//                                                          manifest's byte-identical copy to scripts/store-engine.MANIFEST.json
//           node scripts/sync-store-engine.mjs --check    PREBUILD GATE: exit 1 if FHB's copy differs from its manifest
//                                                          (a hand edit) or matches neither SMP origin/dev nor origin/main
//                                                          (drifted: re-run the sync). When the SMP repo is not on this
//                                                          machine (CF build) only the manifest half runs, and says so.
// Never edit FHB's copy by hand; change the engine in SMP. Repo is detected by the presence of src/store-engine/.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const FILES = [
	'lib/storeEngine.ts',
	'lib/farBand.ts',
	'lib/firstOrderGuard.ts',
	'lib/marginGuard.ts',
	'lib/order-pricing.ts',
	'lib/shipCountries.ts',
	'data/book-skus.json',
	'data/book-us-costs.json', // server-only measured US costs (FHB 894075c moved them out of book-skus.json)
	'data/books.json',
	'data/isbn-list.json',
	'data/ship-countries.json',
];
export const DEST = 'src/store-engine'; // the MASTER, in SMP
export const MANIFEST = path.join(DEST, 'MANIFEST.json');
export const FHB_MANIFEST = 'scripts/store-engine.MANIFEST.json'; // FHB's byte-identical copy of MANIFEST
export const SMP_REPO = process.env.SMP_REPO || '/srv/sites/spirit-media-publishing';
export const sha = (b) => createHash('sha256').update(b).digest('hex');
export const destOf = (f) => path.join(DEST, f); // SMP master path
export const fhbOf = (f) => path.join('src', f); // FHB copy path
export const manifestOf = (files) =>
	`${JSON.stringify(
		{
			_about:
				'GENERATED by scripts/sync-store-engine.mjs. MASTER = SMP src/store-engine/; FHB holds a byte-identical copy (src/lib + src/data). Do not edit.',
			master: 'spirit-media-publishing src/store-engine/',
			files,
		},
		null,
		'\t', // tabs = what biome writes on commit, so the stamp is a fixed point
	)}\n`;

// GIT_* stripped: under `git pushd` (a git alias) GIT_DIR points at the CALLING repo, and `git -C <SMP>` would then read
// FHB's refs and report a false drift (2026-11-16, first FHB pushd after the switch).
const gitEnv = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('GIT_')));
const git = (dir, args) =>
	execFileSync('git', ['-C', dir, ...args], { encoding: 'buffer', stdio: ['ignore', 'pipe', 'pipe'], env: gitEnv });
const shaAtRef = (ref) => {
	const out = {};
	for (const f of FILES) out[f] = sha(git(SMP_REPO, ['show', `${ref}:${destOf(f)}`]));
	return out;
};
const same = (a, b) => FILES.every((f) => a[f] === b[f]);
const die = (m) => {
	console.error(`✗ store-engine: ${m}`);
	process.exit(1);
};

// Exit-code check of a set of files against a manifest; returns the list of offending paths.
export function offManifest(man, pathOf) {
	if (JSON.stringify(Object.keys(man.files).sort()) !== JSON.stringify([...FILES].sort())) return ['<manifest file list>'];
	return FILES.filter((f) => !fs.existsSync(pathOf(f)) || sha(fs.readFileSync(pathOf(f))) !== man.files[f]).map(pathOf);
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const argv = process.argv.slice(2);
	const check = argv.includes('--check');
	const from = argv.includes('--from') ? argv[argv.indexOf('--from') + 1] : null;
	const isSmp = fs.existsSync(DEST);

	if (isSmp) {
		if (check) {
			const bad = offManifest(JSON.parse(fs.readFileSync(MANIFEST, 'utf8')), destOf);
			if (bad.length) die(`${bad.join(', ')} differ(s) from ${MANIFEST}: run node scripts/sync-store-engine.mjs and commit both`);
			console.log(`store-engine: master ok, ${FILES.length} files match ${MANIFEST}`);
		} else {
			const files = Object.fromEntries(FILES.map((f) => [f, sha(fs.readFileSync(destOf(f)))]));
			fs.writeFileSync(MANIFEST, manifestOf(files));
			console.log(`store-engine: stamped ${MANIFEST} (${FILES.length} files). FHB picks it up with its own sync.`);
		}
	} else if (check) {
		// FHB prebuild gate
		if (!fs.existsSync(FHB_MANIFEST)) die(`${FHB_MANIFEST} missing: run node scripts/sync-store-engine.mjs`);
		const man = JSON.parse(fs.readFileSync(FHB_MANIFEST, 'utf8'));
		const bad = offManifest(man, fhbOf);
		if (bad.length) die(`${bad.join(', ')} edited by hand in FHB. The engine's master is SMP src/store-engine/: change it there, then run node scripts/sync-store-engine.mjs here`);
		if (!fs.existsSync(path.join(SMP_REPO, '.git'))) {
			console.log(`store-engine: FHB copy matches its manifest; SMP repo ${SMP_REPO} not on this machine, drift half skipped`);
		} else {
			try {
				git(SMP_REPO, ['fetch', '-q', 'origin', 'dev', 'main']);
			} catch {
				console.log('store-engine: (fetch of SMP failed; comparing to the refs already fetched)');
			}
			const hit = ['origin/dev', 'origin/main'].find((r) => {
				try {
					return same(man.files, shaAtRef(r));
				} catch {
					return false;
				}
			});
			if (!hit) die(`FHB's copy drifted from SMP's master (matches neither SMP origin/dev nor origin/main): run node scripts/sync-store-engine.mjs and commit src/lib, src/data and ${FHB_MANIFEST}`);
			console.log(`store-engine: FHB copy = SMP master at ${hit} (${FILES.length} files)`);
		}
	} else {
		// FHB: pull the master in
		let read;
		let label;
		if (from) {
			read = (p) => fs.readFileSync(path.join(from, p));
			label = `${from} (working tree)`;
		} else {
			try {
				git(SMP_REPO, ['fetch', '-q', 'origin', 'dev']);
			} catch {
				console.log('store-engine: (fetch of SMP failed; using origin/dev as already fetched)');
			}
			read = (p) => git(SMP_REPO, ['show', `origin/dev:${p}`]);
			label = `${SMP_REPO} origin/dev@${git(SMP_REPO, ['rev-parse', '--short', 'origin/dev']).toString().trim()}`;
		}
		const manBytes = read(MANIFEST);
		const man = JSON.parse(manBytes.toString('utf8'));
		const bytes = Object.fromEntries(FILES.map((f) => [f, read(destOf(f))]));
		const off = FILES.filter((f) => sha(bytes[f]) !== man.files?.[f]);
		if (off.length) die(`SMP master ${label}: ${off.join(', ')} differ(s) from its MANIFEST.json (unstamped edit in SMP) — refusing to copy`);
		for (const f of FILES) {
			fs.mkdirSync(path.dirname(fhbOf(f)), { recursive: true });
			fs.writeFileSync(fhbOf(f), bytes[f]);
		}
		fs.writeFileSync(FHB_MANIFEST, manBytes);
		console.log(`store-engine: ${FILES.length} files + manifest copied from SMP ${label}`);
	}
}
