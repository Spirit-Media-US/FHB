import registry from './edition-registry.json' with { type: 'json' };
import roster from './language-roster.json' with { type: 'json' };

export interface LanguageEdition {
	code: string;
	name: string;
	english: string;
	/** card line: "For " + the sheet's For box (fors.d/lang-<code>.json), as approved */
	sub: string;
	amazon?: { hardback?: string; paperback?: string };
	/** false = press files not delivered yet: counted in the 26, never shown. */
	ready?: boolean;
	/** card art is the edition's DESIGNED front (locked 74-cover set, language-bible-titles) because
	 *  its press cover is not delivered yet (Kevin 2026-10-03: use it meanwhile). Swap to the
	 *  delivered case PDF via build_lang_cards.py under a NEW R2 key when it lands. */
	design?: boolean;
	/** coming soon (Kevin 2026-10-07): counted in the 33 and named, never given a card, page or
	 *  order form — no built cover or interior yet. Drop it when both land. */
	soon?: boolean;
	/** right-to-left script */
	rtl?: boolean;
}

export const LANG_HB = 99.99;
export const LANG_PB = 79.99;

// THE LIST IS NOT TYPED HERE ANY MORE (Kevin 2026-10-07, "1 yes 2. a"). It is
// src/data/edition-registry.json, GENERATED by `/home/deploy/bin/fhb-chain.py edition-emit` from
// the facts the work itself writes: the publisher's Ingram submission log (an edition is listed
// once BOTH bindings carry an Ingram CSS id), ISBNS.json, the edition decks and the locked title
// master (name), fors.d (English name + the For line), the delivered press files on Drive (card
// cut from the BUILT case), and claude-config/editions/amazon-listings.json (Amazon, ISBN-matched).
// Amharic and Zulu are listed early by Kevin's ruling and render as `soon` until their covers are
// built. The registry is alphabetical by English name, as /print is. Never hand-edit it — fix the
// fact; the edition chain re-emits it and ships it.
export const allLanguageEditions: LanguageEdition[] = registry.editions.map((e) => ({
	code: e.code,
	name: e.name,
	english: e.english,
	sub: e.sub,
	...('rtl' in e && e.rtl ? { rtl: true } : {}),
	...('soon' in e && e.soon ? { soon: true } : {}),
	...('amazon' in e && e.amazon && Object.keys(e.amazon).length ? { amazon: e.amazon } : {}),
}));

/** Every language edition (Kevin's 33), shown or not. */
export const LANGUAGE_EDITION_TOTAL = allLanguageEditions.length;
/** The editions with delivered covers — the only ones any page renders. */
export const languageEditions = allLanguageEditions.filter((l) => l.ready !== false && !l.soon);
/** Named on /print as coming soon; nothing else renders them. */
export const comingSoonEditions = allLanguageEditions.filter((l) => l.soon);

/** URL/data slug for an edition's product page and look-inside: "spanish" → /bibles/spanish-bible/ */
export const langSlug = (l: LanguageEdition) =>
	l.english
		.replace(/\s*\(.*\)/, '')
		.toLowerCase()
		.replace(/[^a-z]+/g, '-');

